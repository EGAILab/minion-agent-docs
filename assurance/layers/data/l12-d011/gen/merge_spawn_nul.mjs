const [winPath, linuxPath, outPath] = process.argv.slice(2);
const parts = { win32: JSON.parse(readFileSync(winPath, "utf8")), linux: JSON.parse(readFileSync(linuxPath, "utf8")) };
for (const [p, d] of Object.entries(parts)) if (d.platform !== p || d.node !== "22.15.1") throw new Error(`bad partial ${p}`);
const S = (s) => ({ utf16: Array.from({ length: s.length }, (_, i) => s.charCodeAt(i)) });

function expectFor(c, platform) {
  if (c.pre_aborted) return { code: "aborted" };
  const r = parts[platform].cases[c.id];
  if (!r) throw new Error(`missing ${platform} result for ${c.id}`);
  if (c.minion_offending_entry && r.node.outcome !== "nul_diagnostic") {
    // Node dropped the offending case-colliding entry (Windows) -- Minion's retained-entry diagnostic applies.
    if (platform !== "win32") throw new Error(`unexpected non-diagnostic on ${platform} for ${c.id}`);
    return { code: "spawn_error", message: { utf16: r.minion_entry_diagnostic.message }, node_contrast: "spawned (entry dropped)" };
  }
  if (r.node.outcome === "nul_diagnostic") {
    if (c.control) throw new Error(`control ${c.id} produced a NUL diagnostic`);
    return { code: "spawn_error", message: { utf16: r.node.message } };
  }
  if (!c.control) throw new Error(`${c.id} on ${platform} did not produce a diagnostic`);
  return { code: "spawn_error", message: "os" };
}

const cases = CASES.map((c) => ({
  id: c.id,
  argv: c.argv.map(S),
  cwd: c.cwd === null ? null : S(c.cwd),
  env: c.env === null ? null : c.env.map(([k, v]) => [S(k), S(v)]),
  inherit_env: c.inherit_env,
  pre_aborted: c.pre_aborted,
  expect: { win32: expectFor(c, "win32"), linux: expectFor(c, "linux") },
}));
const tools = TOOL_CASES.map((t) => {
  const exp = {};
  const args = {};
  for (const p of ["win32", "linux"]) {
    args[p] = Object.fromEntries(Object.entries(t.arguments[p] ?? t.arguments.any).map(([k, v]) => [k, S(v)]));
    if (t.pre_aborted) { exp[p] = { is_error: true, text: S("Operation aborted") }; continue; }
    const r = parts[p].tools[t.id];
    if (r.outcome !== "error" || r.code !== "ERR_INVALID_ARG_VALUE") throw new Error(`tool ${t.id} on ${p}: ${JSON.stringify(r).slice(0, 200)}`);
    exp[p] = { is_error: true, text: { utf16: r.text } };
  }
  return { id: t.id, tool: t.tool, arguments: args, pre_aborted: !!t.pre_aborted, expect: exp };
});
