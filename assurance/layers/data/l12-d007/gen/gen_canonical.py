"""Merge the per-platform pinned-Pi oracle outputs into the canonical fs_path_domain file.

    python gen_canonical.py <oracle-win32.json> <oracle-linux.json> <out fs-error-codes.json>

A step whose observation is identical on every platform the case runs on gets `expect`; otherwise
`expect_by_platform`. Before writing, every operation cell is cross-checked against the independent
characterization runs (../pi-win32.json, ../pi-linux.json): the two Pi runs must agree on the code.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
cases = json.load(open(os.path.join(HERE, "cases.json"), encoding="utf-8"))["cases"]
oracle = {"win32": json.load(open(sys.argv[1], encoding="utf-8")), "linux": json.load(open(sys.argv[2], encoding="utf-8"))}
by_id = {p: {r["id"]: r["observed"] for r in o["results"]} for p, o in oracle.items()}

# Cross-check against the characterization matrix (record section 2): same condition/operation -> same code.
CHAR_OP = {"read_text_file": "readTextFile", "read_text_lines": "readTextLines", "read_binary_file": "readBinaryFile",
           "write_file": "writeFile", "append_file": "appendFile", "rename_file-source": "renameFile-source",
           "rename_file-onto": "renameFile-destination-onto", "file_info": "fileInfo", "exists": "exists",
           "list_dir": "listDir", "canonical_path": "canonicalPath", "create_dir-recursive": "createDir-recursive",
           "create_dir-nonrecursive": "createDir-nonrecursive", "remove": "remove", "remove-recursive": "remove-recursive",
           "remove-force": "remove-force"}
mismatch = 0
for platform, char_file in (("win32", "pi-win32.json"), ("linux", "pi-linux.json")):
    char = {(r["condition"], r["op"]): r["observed"] for r in json.load(open(os.path.join(HERE, "..", char_file), encoding="utf-8"))["results"]}
    for cid, observed in by_id[platform].items():
        _, condition, op = cid.split("/")
        c = char.get((condition, CHAR_OP[op]))
        if c is None:
            continue
        code = observed[-1].get("error", "ok") if "error" in observed[-1] else "ok"
        ccode = c.get("error", "ok") if "error" in c else "ok"
        if code != ccode:
            mismatch += 1
            print(f"MISMATCH {platform} {cid}: oracle={code} characterization={ccode}")
if mismatch:
    sys.exit(f"{mismatch} oracle/characterization mismatches; refusing to generate")

out_cases = []
for c in cases:
    plats = c["platforms"]
    steps = []
    for i, step in enumerate(c["steps"]):
        obs = {p: by_id[p][c["id"]][i] for p in plats}
        s = dict(step)
        if len({json.dumps(v, sort_keys=True) for v in obs.values()}) == 1:
            s["expect"] = obs[plats[0]]
        else:
            s["expect_by_platform"] = obs
        steps.append(s)
    entry = {"id": c["id"], "steps": steps}
    if plats != ["linux", "win32"]:
        entry["platforms"] = plats
        entry["platform_note"] = "Windows-only condition: the host has no such name class / sharing / byte-range-lock semantics on Linux."
    out_cases.append(entry)

doc = {
    "name": "fs-error-codes",
    "family": "agent",
    "authority": ("pinned Pi b7bb00b9 packages/agent/src/harness/env/nodejs.ts NodeExecutionEnv (imported unmodified) under "
                  "Node 22.15.1 / libuv 1.49.2; Windows 11 and Linux (node:22.15.1-bookworm-slim, uid 1000); "
                  "fixture-only steps build the OS condition natively"),
    "pi_revision": "b7bb00b936dbe21b8e160b3e89efdec361846699",
    "requirements": ["EXEC-002"],
    "witnesses": ["fs_error_codes_pinned_pi_literal"],
    "platforms": ["linux", "win32"],
    "notes": ("L12-D007 (minion-agent#199; #69 / #125 / #67): each Pi-derived filesystem operation answers pinned Pi's literal "
              "toFileError code for its input and host platform. GENERATED by assurance/layers/data/l12-d007/gen; do not edit."),
    "fs_path_domain": {"cases": out_cases},
}
with open(sys.argv[3], "w", encoding="utf-8", newline="\n") as f:
    json.dump(doc, f, indent=1, ensure_ascii=False)
    f.write("\n")
print(f"{len(out_cases)} cases -> {sys.argv[3]}; cross-check vs characterization: 0 mismatches")
