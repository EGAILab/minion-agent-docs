"""L12-D005: write conformance/agent/fs-remove-readonly/*.json from cases.json plus the pinned-Pi oracle
outputs (pi-win32.json, pi-linux.json). A case that runs on both platforms must give identical Pi results
on both, or generation fails (the corpus then needs per-platform expectations, which this schema does not
yet carry). Usage: python gen-canonical.py <gen dir> <code worktree root>"""

import json
import pathlib
import sys

gen, root = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
cases = json.loads((gen / "cases.json").read_text(encoding="utf-8"))["cases"]
oracle = {}
for platform in ("win32", "linux"):
    data = json.loads((gen / f"pi-{platform}.json").read_text(encoding="utf-8"))
    assert data["node"] == "22.15.1", data["node"]
    oracle[platform] = {r["id"]: r for r in data["results"]}

out = root / "conformance" / "agent" / "fs-remove-readonly"
out.mkdir(parents=True, exist_ok=True)
for old in out.glob("*.json"):
    old.unlink()
for case in cases:
    platforms = case.get("platforms", ["linux", "win32"])
    observed = [oracle[p][case["id"]] for p in platforms]
    first = observed[0]
    for other in observed[1:]:
        assert (other["observed"], other["left"], other["external"]) == (first["observed"], first["left"], first["external"]), case["id"]
    expect = {"ok": True} if first["observed"].get("ok") else {"error": first["observed"]["error"], "path": first["observed"]["path"]}
    body = {"fixture": case["fixture"], "remove": case["remove"], "expect": expect, "expect_left": first["left"]}
    if case.get("external"):
        body["expect_external"] = first["external"]
    doc = {
        "name": f"fs-remove-readonly-{case['id']}",
        "authority": ("pinned Pi b7bb00b9 packages/agent/src/harness/env/nodejs.ts NodeExecutionEnv.remove (imported "
                      "unmodified), Node v22.15.1 / libuv 1.49.2 (Windows unlink/rmdir use "
                      "FILE_DISPOSITION_IGNORE_READONLY_ATTRIBUTE), on " + " and ".join(platforms)),
        "pi_revision": "b7bb00b936dbe21b8e160b3e89efdec361846699",
        "requirements": ["EXEC-002"],
        "platforms": platforms,
        "notes": "L12-D005 (minion-agent#188, provenance #126). GENERATED by assurance/layers/data/l12-d005/gen; do not edit.",
        "fs_remove": body,
    }
    (out / f"fs-remove-readonly-{case['id']}.json").write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(len(cases), "documents")
