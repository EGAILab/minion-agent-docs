"""L0506-D005: write conformance/agent/arg-isolation/*.json from cases.json and the pinned-Pi oracle output
(pi-oracle.json, from ../harness/run.sh). Usage: python gen_canonical.py <gen dir> <oracle json> <code worktree root>"""

import json
import pathlib
import sys

gen, oracle_path, root = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
cases = json.loads((gen / "cases.json").read_text(encoding="utf-8"))["cases"]
oracle = json.loads(oracle_path.read_text(encoding="utf-8"))
assert oracle["node"] == "22.15.1", oracle["node"]
assert oracle["pi"] == "b7bb00b936dbe21b8e160b3e89efdec361846699"
results = {r["id"]: r for r in oracle["results"]}
assert set(results) == {c["id"] for c in cases}

out = root / "conformance" / "agent" / "arg-isolation"
out.mkdir(parents=True, exist_ok=True)
for old in out.glob("*.json"):
    old.unlink()
for case in cases:
    observed = results[case["id"]]
    scenario = {"raw_text": case["text"]}
    for key in ("schema", "prepare"):
        if key in case:
            scenario[key] = case[key]
    scenario["hooks"] = case["hooks"]
    if case.get("block"):
        scenario["block"] = True
    if case.get("facts"):
        scenario["facts"] = case["facts"]
    scenario["expect"] = {
        "outcome": observed["outcome"],
        "hook_entries": observed["hook_entries"],
        "facts": observed["facts"],
        "execute": observed["execute"],
        "updates": observed["updates"],
        "raw_after": observed["raw_after"],
    }
    doc = {
        "name": f"arg-isolation-{case['id']}",
        "authority": ("pinned Pi b7bb00b9 agent-loop.ts prepareToolCall/executePreparedToolCall and validation.ts "
                      "validateToolArguments (structuredClone), sliced unmodified; Node v22.15.1; typebox 1.3.7"),
        "pi_revision": "b7bb00b936dbe21b8e160b3e89efdec361846699",
        "requirements": ["TOOL-003"],
        "notes": "L0506-D005 (minion-agent#190, provenance #129). GENERATED by assurance/layers/data/l0506-d005/gen; do not edit.",
        "arg_isolation": scenario,
    }
    (out / f"{doc['name']}.json").write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"{len(cases)} documents")
