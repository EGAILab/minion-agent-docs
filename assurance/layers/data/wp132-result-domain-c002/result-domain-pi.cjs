// Real pinned functions, with erased TypeScript only; no reimplemented edit/diff.
const fs = require('fs');
const crypto = require('crypto');
const assert = require('assert/strict');
const cp = require('child_process');
const {stripTypeScriptTypes} = require('node:module');
assert.equal(process.version, 'v22.15.1');
const root = process.cwd();
const pi = root + '/ref-repos/pi';
const pin = 'b7bb00b936dbe21b8e160b3e89efdec361846699';
const git = args => cp.execFileSync('git', ['-c', 'safe.directory='+pi.replaceAll('\\','/'), '-C', pi, ...args], {encoding:'utf8'}).trim();
assert.equal(git(['rev-parse','HEAD']),pin);
assert.equal(git(['status','--porcelain']),'');
const lock = JSON.parse(cp.execFileSync('git',['-c','safe.directory='+pi.replaceAll('\\','/'),'-C',pi,'show',pin+':package-lock.json'],{encoding:'utf8'}));
const archive = root + '/.tmp/replay/diff-8.0.4.tgz';
assert.equal('sha512-'+crypto.createHash('sha512').update(fs.readFileSync(archive)).digest('base64'),lock.packages['node_modules/diff'].integrity);
const stage = root + '/.tmp/wp132-rust/result-domain-stage';
fs.mkdirSync(stage,{recursive:true});
cp.execFileSync('tar',['-xzf',archive,'-C',stage]);
const Diff = require(stage+'/package');
let source = fs.readFileSync(pi+'/packages/coding-agent/src/core/tools/edit-diff.ts','utf8');
source = stripTypeScriptTypes(source).replace(/^import .*;\s*$/gm,'').replace(/\bexport /g,'');
const api = new Function('Diff', source+'\nreturn {applyEditsToNormalizedContent,generateDiffString,generateUnifiedPatch};')(Diff);
const edit = fs.readFileSync(pi+'/packages/coding-agent/src/core/tools/edit.ts','utf8');
const single = edit.slice(edit.indexOf('function isSingleEditInput('),edit.indexOf('export interface EditToolDetails'));
const prepare = edit.slice(edit.indexOf('function prepareEditArguments('),edit.indexOf('function validateEditInput('));
const prepareEdit = new Function(stripTypeScriptTypes(single+prepare)+'\nreturn prepareEditArguments;')();
const args = prepareEdit({path:'f.txt',edits:'[{"oldText":"a","newText":"\\ud800"}]'});
const {baseContent,newContent} = api.applyEditsToNormalizedContent('a\n',args.edits,'f.txt');
const details = {...api.generateDiffString(baseContent,newContent),patch:api.generateUnifiedPatch('f.txt',baseContent,newContent)};
assert.equal(Buffer.from(newContent,'utf8').toString('hex'),'efbfbd0a');
assert.ok(details.diff.includes(String.fromCharCode(0xd800)));
assert.ok(details.patch.includes(String.fromCharCode(0xd800)));
assert.ok(!details.diff.includes('\ufffd'));
console.log(JSON.stringify({pi:pin,prepared_units:[...args.edits[0].newText].map(c=>c.charCodeAt(0)),file_utf8_hex:Buffer.from(newContent,'utf8').toString('hex'),details}));
