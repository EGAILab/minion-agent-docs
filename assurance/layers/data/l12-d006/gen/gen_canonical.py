"""L12-D006: write conformance/agent/fs-path-domain/fs-path-nul.json from cases.json and the pinned-Pi oracle
outputs (pi-win32.json, pi-linux.json). Every case must observe identically on both platforms, or generation
fails. Usage: python gen_canonical.py <gen dir> <code worktree root>"""

import json
import pathlib
import sys

gen, root = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
cases = json.loads((gen / "cases.json").read_text(encoding="utf-8"))["cases"]
oracle = {}
for platform in ("win32", "linux"):
    data = json.loads((gen / f"pi-{platform}.json").read_text(encoding="utf-8"))
    assert data["node"] == "22.15.1" and data["pi"] == "b7bb00b936dbe21b8e160b3e89efdec361846699"
    oracle[platform] = {r["id"]: r["observed"] for r in data["results"]}
out_cases = []
for case in cases:
    observed = oracle["win32"][case["id"]]
    assert observed == oracle["linux"][case["id"]], case["id"]
    assert len(observed) == len(case["steps"])
    out_cases.append({"id": case["id"], "steps": [{**s, "expect": o} for s, o in zip(case["steps"], observed)]})
document = {
    "name": "fs-path-nul",
    "family": "agent",
    "authority": ("pinned Pi b7bb00b9 packages/agent/src/harness/env/nodejs.ts NodeExecutionEnv (imported unmodified) + "
                  "coding-agent core/tools/file-mutation-queue.ts getMutationQueueKey (sliced unmodified); Minion-only "
                  "operations by the pinned Node primitive they map (readdir / lstat / access); Node 22.15.1; identical "
                  "on Linux (node:22.15.1-bookworm-slim, uid 1000) and Windows 11"),
    "pi_revision": "b7bb00b936dbe21b8e160b3e89efdec361846699",
    "requirements": ["EXEC-002", "EXEC-003"],
    "witnesses": ["fs_path_nul_unknown"],
    "platforms": ["linux", "win32"],
    "notes": ("L12-D006 (minion-agent#65 + #133-F1): a NUL-containing path. The native call whose path argument carries "
              "the NUL fails as `unknown` with the logical fallback path, in each operation's own call order; lexical "
              "operations, max_lines <= 0 and abort keep their precedence. GENERATED by "
              "assurance/layers/data/l12-d006/gen; do not edit."),
    "fs_path_domain": {"cases": out_cases},
}
target = root / "conformance" / "agent" / "fs-path-domain" / "fs-path-nul.json"
target.write_text(json.dumps(document, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"{len(out_cases)} cases -> {target.name}")
